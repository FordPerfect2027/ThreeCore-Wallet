import {readFileSync,writeFileSync,existsSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import assert from 'node:assert/strict';
const base='C:/Users/aseet/Documents/Codex/2026-10-26/test-4/work/';
const tokens=[['DAT','DATCore'],['EMA','EMACore'],['CAWELON','CAWELONCore']];
const sha=b=>createHash('sha256').update(b).digest('hex');
const template=base+'token-dependency-repair-DAT-20261102';
const result=[];
for(const[token,contract]of tokens){
 const root=base+'token-dependency-repair-'+token+'-20261102',path='contracts/'+contract+'.sol';
 const before=readFileSync(root+'/'+path),text=before.toString(),after=Buffer.from(text.replaceAll('\r\n','\n'));
 assert(text.includes('\r\n'));assert(!after.includes(13));
 const artifactBytes=readFileSync(root+'/artifacts/'+path+'/'+contract+'.json'),artifact=JSON.parse(artifactBytes);
 result.push({token,contract,root,parent:execFileSync('git',['rev-parse','HEAD'],{cwd:root,encoding:'utf8'}).trim(),sourceBeforeSha256:sha(before),sourceAfterSha256:sha(after),onlyCrLfChanged:before.toString().replaceAll('\r\n','\n')===after.toString(),artifactBeforeSha256:sha(artifactBytes),artifactBefore:{abi:artifact.abi,bytecode:artifact.bytecode,deployedBytecode:artifact.deployedBytecode,immutableReferences:artifact.immutableReferences},lockSha256:sha(readFileSync(root+'/package-lock.json'))});
 writeFileSync(root+'/'+path,after);
 const attr=root+'/.gitattributes';
 writeFileSync(attr,(existsSync(attr)?readFileSync(attr,'utf8'):'')+'\n# Solidity metadata hashes source bytes; use LF on every platform.\n/contracts/** text eol=lf\n');
 for(const file of ['scripts/check-contract-source.js','integration/source-portability.test.mjs'])if(root!==template)writeFileSync(root+'/'+file,readFileSync(template+'/'+file));
 const packagePath=root+'/package.json',old=readFileSync(packagePath,'utf8');
 assert(old.includes('"compile": "hardhat compile"'));
 writeFileSync(packagePath,old.replace('"compile": "hardhat compile"','"compile": "node scripts/check-contract-source.js && hardhat compile"').replace('"check": "npm run compile','"check": "npm run test:source && npm run compile').replace('"test:history":','"test:source": "node --test integration/source-portability.test.mjs",\r\n    "test:history":'));
 const doc=`# Deterministic contract source bytes — November 2, 2026

Solidity metadata contains source hashes. Changing CRLF to LF can therefore
change the bytecode metadata even when contract logic stays identical. DAT's
historical verifier exposed this difference against its recorded deployment.

The contracts directory now has a narrow Git LF checkout policy. This change
normalizes the existing ${contract}.sol line endings only; it changes no Solidity
statement, compiler setting, dependency, deployment record or expected hash.
It does change the generated bytecode metadata and artifact fingerprint. Rebuild
and review the new artifact rather than labelling it byte-identical to the old one.

The compile command first checks that all Solidity sources use UTF-8 without
BOM and contain no CR. It fails before starting Hardhat if they do not, leaving
the source untouched. The check uses local files only. The source regression
creates isolated Git repositories and checks actual source bytes after checkout
with both autocrlf settings, and verifies CRLF/BOM/invalid-UTF-8 rejection.

Run npm run test:source followed by npm run compile. The ordinary npm run check
also includes the source regression. Existing clones with converted files must
save the contracts using LF before building; no automatic source rewrite occurs
during compilation. Source hashes and fresh-build comparisons are recorded in
the Wallet evidence collection. No live deployment is updated by this change.
`;
 writeFileSync(root+'/docs/SOURCE_PORTABILITY_2026-11-02.md',doc);
 const readme=root+'/README.md';writeFileSync(readme,readFileSync(readme,'utf8')+'\n[Contract source portability](docs/SOURCE_PORTABILITY_2026-11-02.md): compilation requires UTF-8/LF source bytes so platform line-ending conversion cannot silently change the candidate artifact.\n');
}
writeFileSync('C:/Users/aseet/Downloads/ThreeCore-source-portability-before-20261102.json',JSON.stringify(result,null,2)+'\n');
