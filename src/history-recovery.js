import { createPortfolioHistory } from "./portfolio-history.js";
import { reviewHistoryImport } from "./history-review.js";
import { prepareHistoryRecoveryReport } from "./history-recovery-report.js";

export class HistoryRecoveryError extends Error {
  constructor(code, message) {
    super(message);
    this.name = "HistoryRecoveryError";
    this.code = code;
  }
}
function fail(code, message) { throw new HistoryRecoveryError(code, message); }

/**
 * Keep exactly one bounded pre-deletion/replacement archive in memory.
 * There is no persistence, RPC or wallet capability. Recovery must be reviewed
 * and applied explicitly while the destination is still exactly as expected.
 */
export function createHistoryRecovery(history) {
  if (!history || typeof history.exportText !== "function" || typeof history.state !== "function") {
    throw new TypeError("A history collection is required");
  }
  let backup = null;
  let proposal = null;
  let sequence = 0;
  let previewSequence = 0;
  let disposed = false;
  function active() {
    if (disposed) fail("RECOVERY_DISPOSED", "Recovery controller is disposed");
  }
  function currentRevision(expected) {
    active();
    if (expected !== history.state().revision) fail("STALE_HISTORY", "Review current history before changing it");
  }
  function before(expected) {
    currentRevision(expected);
    return { text: history.exportText(), revision: expected, size: history.state().size };
  }
  function remember(previous, kind) {
    const current = history.state();
    proposal = null;
    if (current.revision === previous.revision) return;
    backup = Object.freeze({
      recoveryId: ++sequence,
      text: previous.text,
      previousCount: previous.size,
      resultingCount: current.size,
      expectedRevision: current.revision,
      expectedText: history.exportText(),
      kind,
    });
  }
  function remove(index, expectedRevision) {
    const previous = before(expectedRevision);
    const result = history.remove(index, expectedRevision);
    remember(previous, "remove");
    return result;
  }
  function clear(expectedRevision) {
    const previous = before(expectedRevision);
    const result = history.clear(expectedRevision);
    remember(previous, "clear");
    return result;
  }
  function replace(text, expectedRevision) {
    const previous = before(expectedRevision);
    // The model already guarantees atomic schema/capacity validation.
    const result = history.importText(text, { replace: true });
    remember(previous, "replace");
    return result;
  }
  function state() {
    const current = history.state();
    const matches = !disposed && backup !== null &&
      current.revision === backup.expectedRevision && history.exportText() === backup.expectedText;
    return Object.freeze({
      hasBackup: !disposed && backup !== null,
      canPreview: matches,
      recoveryId: !disposed ? backup?.recoveryId ?? null : null,
      kind: !disposed ? backup?.kind ?? null : null,
      previousCount: !disposed ? backup?.previousCount ?? 0 : 0,
      resultingCount: !disposed ? backup?.resultingCount ?? 0 : 0,
      currentCount: current.size,
      currentRevision: current.revision,
      previewPending: !disposed && proposal !== null,
      previewId: !disposed ? proposal?.previewId ?? null : null,
      storage: "memory-only",
      canAuthorizeConnection: false,
      canAuthorizeTransaction: false,
    });
  }
  function preview() {
    active();
    proposal = null;
    if (!backup) fail("NO_RECOVERY", "No saved recovery archive");
    if (!state().canPreview) fail("STALE_HISTORY", "History changed after deletion; use a separate reviewed import");
    const impact = reviewHistoryImport(history.exportText(), backup.text, { replace: true });
    proposal = Object.freeze({
      previewId: ++previewSequence,
      recoveryId: backup.recoveryId,
      expectedRevision: history.state().revision,
      expectedText: history.exportText(),
      impact,
    });
    return proposal;
  }
  function apply(previewId) {
    active();
    const reviewed = proposal;
    proposal = null;
    if (!reviewed || reviewed.previewId !== previewId || !backup ||
        reviewed.recoveryId !== backup.recoveryId) fail("MISSING_RECOVERY_PREVIEW", "Preview recovery again");
    if (!state().canPreview || history.state().revision !== reviewed.expectedRevision ||
        history.exportText() !== reviewed.expectedText) fail("STALE_HISTORY", "Do not overwrite newer observations");
    const result = history.importText(backup.text, { replace: true });
    backup = null;
    return result;
  }
  function cancelPreview() { proposal = null; }
  function exportText() {
    active();
    if (!backup) fail("NO_RECOVERY", "No saved recovery archive");
    // Revalidate even though the internal archive was generated by the model.
    const check = createPortfolioHistory();
    check.importText(backup.text);
    return check.exportText();
  }
  function report() {
    active();
    return prepareHistoryRecoveryReport(history, { state, exportText });
  }
  function discard(recoveryId) {
    active();
    if (!backup || recoveryId !== backup.recoveryId) fail("STALE_RECOVERY", "Review the current recovery slot");
    backup = null;
    proposal = null;
  }
  function dispose() {
    backup = null;
    proposal = null;
    disposed = true;
  }
  return Object.freeze({ state, remove, clear, replace, preview, apply, cancelPreview, exportText, report, discard, dispose });
}
